// localwp-test 的瀏覽器工具模組。自訂測試腳本可用 require('lwp-browser') 取得。
// 連線到 `lwp <站台> browser start` 啟動的無頭瀏覽器（Edge／Chrome）（直接 launch 在部分 Windows 環境會立刻結束）。
const fs = require('fs');
const path = require('path');
const puppeteer = require('puppeteer-core');

const OUT = process.env.LWP_OUT || process.cwd();
const CDP = process.env.LWP_CDP || 'http://127.0.0.1:9333';
const COOKIES = path.join(OUT, 'cookies.txt');

function meta() {
	try { return JSON.parse(fs.readFileSync(COOKIES + '.meta', 'utf8')); } catch (e) { return {}; }
}
const BASE = (process.env.LWP_BASE || meta().home || '').replace(/\/$/, '');

function loadCookies() {
	if (!fs.existsSync(COOKIES)) return [];
	return fs.readFileSync(COOKIES, 'utf8').split('\n')
		.filter(l => l && !l.startsWith('#'))
		.map(l => {
			const [domain, , p, secure, exp, name, value] = l.split('\t');
			return { name, value, domain, path: p, secure: secure === 'TRUE', expires: Number(exp) };
		});
}

const sleep = ms => new Promise(r => setTimeout(r, ms));

// 只把真正的錯誤記下來：console.error、未捕捉例外、站台本身 4xx/5xx、站台請求失敗（使用者主動中斷的除外）。
function watch(page) {
	const problems = [];
	page.on('console', m => { if (m.type() === 'error') problems.push('console: ' + m.text().slice(0, 300)); });
	page.on('pageerror', e => problems.push('pageerror: ' + String(e.message || e).slice(0, 300)));
	page.on('response', r => { if (BASE && r.url().startsWith(BASE) && r.status() >= 400) problems.push(`HTTP ${r.status()}: ${r.url()}`); });
	page.on('requestfailed', r => {
		const err = (r.failure() || {}).errorText || '';
		if (BASE && r.url().startsWith(BASE) && err !== 'net::ERR_ABORTED') problems.push(`requestfailed: ${r.method()} ${r.url().slice(0, 200)} ${err}`);
	});
	page.on('dialog', async d => { problems.push(`dialog(${d.type()}): ${d.message().slice(0, 200)}`); await d.accept(); });
	return problems;
}

async function connect() {
	try {
		const browser = await puppeteer.connect({ browserURL: CDP, acceptInsecureCerts: true });
		const cookies = loadCookies();
		if (cookies.length) await browser.setCookie(...cookies);
		return browser;
	} catch (e) {
		throw new Error(`無法連到 ${CDP}，請先執行 lwp <站台> browser start（${e.message}）`);
	}
}

/** 開新分頁並（選擇性）前往網址。回傳 { browser, page, problems, close }。 */
async function open(url, { waitMs = 1500, viewport = { width: 1400, height: 1000 } } = {}) {
	const browser = await connect();
	const page = await browser.newPage();
	await page.setViewport(viewport);
	const problems = watch(page);
	let status = null;
	if (url) status = await goto(page, url, { waitMs });
	return { browser, page, problems, status, close: async () => { await page.close(); browser.disconnect(); } };
}

async function goto(page, url, { waitMs = 1500 } = {}) {
	const full = /^https?:/.test(url) ? url : BASE + url;
	const resp = await page.goto(full, { waitUntil: 'load', timeout: 60000 });
	// 有些頁面（字型庫、Connectors 等）會持續連線，永遠等不到網路閒置，所以最多只等 10 秒
	await page.waitForNetworkIdle({ idleTime: 500, concurrency: 2, timeout: 10000 }).catch(() => {});
	await sleep(waitMs); // 給 Knockout／React 等前端框架時間完成初始化
	return resp ? resp.status() : null;
}

async function shot(page, name) {
	const dir = path.join(OUT, 'shots');
	fs.mkdirSync(dir, { recursive: true });
	const file = path.join(dir, name.replace(/[^\w.-]+/g, '_') + '.png');
	await page.screenshot({ path: file });
	return file;
}

/** 頁面上可見的 WordPress 通知文字（排除常見的系統提醒）。 */
async function notices(page) {
	return page.evaluate(() => [...document.querySelectorAll('.notice, .updated, .error, #message')]
		.map(n => n.textContent.trim().replace(/\s+/g, ' ')).filter(Boolean));
}

/** 點擊後等待頁面跳轉（表單送出用）。 */
async function clickAndWait(page, selectorOrHandle) {
	const el = typeof selectorOrHandle === 'string' ? await page.$(selectorOrHandle) : selectorOrHandle;
	if (!el) throw new Error('找不到元素：' + selectorOrHandle);
	await Promise.all([page.waitForNavigation({ waitUntil: 'load', timeout: 60000 }), el.click()]);
	await page.waitForNetworkIdle({ idleTime: 500, concurrency: 2, timeout: 10000 }).catch(() => {});
	await sleep(800);
}

/** PHP 錯誤字樣（WP_DEBUG_DISPLAY 開啟時才會出現在頁面上）。 */
async function phpErrors(page) {
	const html = await page.content();
	const m = html.match(/<b>(Fatal error|Parse error|Warning|Notice|Deprecated)<\/b>:[^<]{0,200}/g) || [];
	if (/There has been a critical error|網站發生嚴重錯誤/.test(html)) m.push('WordPress critical error screen');
	return m;
}

module.exports = { BASE, OUT, sleep, connect, open, goto, shot, notices, clickAndWait, phpErrors, watch };
